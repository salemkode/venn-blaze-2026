// Compiles every contract in contracts/, writes each artifact, the templates the app rebuilds
// the contracts from (src/venn/artifact.ts) and their fingerprints in contracts/registry.json.
// Fails when VennVault or CircleVault embed a VennMoney template that is not the compiled one.
import { compileFile } from 'cashc';
import { Buffer } from 'node:buffer';
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';

const file = name => new URL(`../${name}`, import.meta.url);
const sha256 = hex => createHash('sha256').update(Buffer.from(hex, 'hex')).digest('hex');

const compile = name => {
  const artifact = compileFile(file(`contracts/${name}.cash`));
  artifact.updatedAt = '1970-01-01T00:00:00.000Z';
  writeFileSync(file(`contracts/${name}.json`), JSON.stringify(artifact, null, 2) + '\n');
  const template = artifact.debug.bytecode;
  return {
    name,
    compiler: `${artifact.compiler.name} ${artifact.compiler.version}`,
    constructor: artifact.constructorInputs.map(i => i.name),
    functions: artifact.abi.map(f => f.name),
    template,
    sha256: sha256(template),
  };
};

const money = compile('VennMoney');
const vault = compile('VennVault');
const circle = compile('CircleVault');
for (const name of ['VennVault', 'CircleVault']) {
  const source = readFileSync(file(`contracts/${name}.cash`), 'utf8');
  const embedded = /bytes constant MONEY_TEMPLATE = 0x([0-9a-f]+);/.exec(source)?.[1];
  if (embedded !== money.template)
    throw new Error(`${name} embeds MONEY_TEMPLATE ${embedded}, but VennMoney compiles to ${money.template}`);
}

const entry = c =>
  `{\n  constructor: ${JSON.stringify(c.constructor)},\n  functions: ${JSON.stringify(c.functions)},\n` +
  `  template:\n    '${c.template}',\n  sha256: '${c.sha256}',\n} as const`;
writeFileSync(
  file('src/venn/artifact.ts'),
  '// Generated by scripts/compile-contract.mjs. Do not edit.\n' +
    `export const COMPILER = ${JSON.stringify(vault.compiler)};\n` +
    `export const VAULT = ${entry(vault)};\n` +
    `export const MONEY = ${entry(money)};\n` +
    `export const CIRCLE = ${entry(circle)};\n`,
);

const registry = JSON.parse(readFileSync(file('contracts/registry.json'), 'utf8'));
const set = (name, version, fields) => {
  const found = registry.find(e => e.name === name && e.version === version);
  if (!found) throw new Error(`contracts/registry.json has no ${name} v${version} entry`);
  Object.assign(found, fields);
};
set('Venn', 2, { sha256: vault.sha256, money: money.sha256 });
set('Circle', 1, { sha256: circle.sha256, money: money.sha256 });
writeFileSync(file('contracts/registry.json'), JSON.stringify(registry, null, 2) + '\n');
for (const c of [vault, money, circle])
  console.log(`${c.name}: ${c.template.length / 2} bytes, sha256 ${c.sha256}`);
